import connectDB from "./config/db.js";
import router from './routes/index.js';
import express from 'express';
import swaggerJsDoc from 'swagger-jsdoc';
import { serve, setup } from 'swagger-ui-express';

process.loadEnvFile();

const HOST = process.env.HOST || 'localhost';
const PORT = process.env.PORT || 8080;

const app = express();
connectDB();

//__Configuration________________________________________________

const options = {
    definition: {
        openapi: '3.0.0',
        info: {
            title: 'Contact REST API',
            description: "A REST API built with Express and MongoDB.",
            version: '0.1',
        },
        servers: [
            {
                url: `http://${HOST}:${PORT}/api`,
                description: 'Development server',
            },
        ],
        components: {
            schemas: {
                User: {
                    type: "object",
                    properties: {
                        id: {
                            type: "string",
                            description: "ID generated by MongoDB",
                            example: "6ae4cb639739afbfc794dd66"
                        },
                        email: {
                            type: "string",
                            example: "jane.doe@haddock.com"
                        }
                    }
                },
                NewUser: {
                    type: "object",
                    required: ["email", "password"],
                    properties: {
                        email: {
                            type: "string",
                            example: "jane.doe@haddock.com"
                        },
                        password: {
                            type: "string",
                            example: "password123"
                        }
                    }
                },
                Contact: {
                    type: "object",
                    properties: {
                        id: {
                            type: "string",
                            description: "ID generated by MongoDB",
                            example: "6ae4cb639739afbfc794dd66"
                        },
                        name: {
                            type: "string",
                            example: "Alice"
                        },
                        age: {
                            type: "integer",
                            minimum: 0,
                            example: 25
                        }
                    }
                },
                NewContact: {
                    type: "object",
                    properties: {
                        name: {
                            type: "string",
                            example: "Alice"
                        },
                        age: {
                            type: "integer",
                            minimum: 0,
                            example: 25
                        }
                    }
                },
                UserRegistered: {
                    type: "object",
                    properties: {
                        success: {
                            type: "boolean"
                        },
                        user: {
                            $ref: "#/components/schemas/User"
                        }
                    }
                },
                UserLoggedIn: {
                    type: "object",
                    properties: {
                        success: {
                            type: "boolean"
                        },
                        token: {
                            type: "string",
                            description: "JWT authentication token",
                            example: "eyJhbGciOiJIUzI1NiIs..."
                        }
                    }
                },
                AllContactsResponse: {
                    type: "object",
                    properties: {
                        success: {
                            type: "boolean"
                        },
                        data: {
                            type: "array",
                            items: {
                                $ref: "#/components/schemas/Contact"
                            }
                        },
                        total: {
                            type: "integer",
                            example: 10
                        }
                    }
                },
                SuccessResponse: {
                    type: "object",
                    properties: {
                        success: {
                            type: "boolean"
                        },
                        message: {
                            type: "string"
                        }
                    }
                },
                FailureResponse: {
                    type: "object",
                    properties: {
                        success: {
                            type: "boolean",
                            example: false
                        },
                        status: {
                            type: "integer",
                            example: 500
                        },
                        message: {
                            type: "string",
                            example: "Internal server error"
                        }
                    }
                }
            },
            securitySchemes: {
                bearerAuth: {
                    type: "http",
                    scheme: "bearer",
                    bearerFormat: "JWT"
                }
            }
        }
    },
    apis: ["./src/routes/*.js"],
}

const openapiSpecification = swaggerJsDoc(options);

//__Application configuration____________________________________

app.get('/', (req, res) => {
    res.send('Hi !');
});

app.use(express.json()); // Parse incoming JSON bodies
app.use('/api', router);
app.use('/docs', serve, setup(openapiSpecification));

app.listen(PORT, HOST, () => {
    console.log(`Server is running on http://${HOST}:${PORT}`)
});
